let currentLang = "en";

export function t(key) {
  const dict = i18n[currentLang] || {};
  if (Object.prototype.hasOwnProperty.call(dict, key)) {
    return dict[key];
  }

  if (key.includes('.')) {
    const nestedValue = key.split('.').reduce((acc, part) => {
      if (acc && typeof acc === 'object' && Object.prototype.hasOwnProperty.call(acc, part)) {
        return acc[part];
      }
      return undefined;
    }, dict);

    if (nestedValue !== undefined) {
      return nestedValue;
    }
  }

  return key;
}

export function setLanguage(lang) {
  if (i18n[lang]) {
    currentLang = lang;
    localStorage.setItem('mta-language', lang);
    // Trigger UI update
    if (window.updateAllUI) window.updateAllUI();
  }
}

export function getCurrentLanguage() {
  return currentLang;
}

// Load saved language preference
if (typeof localStorage !== 'undefined') {
  const savedLang = localStorage.getItem('mta-language');
  if (savedLang && i18n[savedLang]) {
    currentLang = savedLang;
  }
}


